namespace CryptoBase.Internal;

internal static class Pkcs1DigestInfo
{
	// The DER encoding of the DigestInfo of each hash up to the hash value, with NULL parameters (RFC 8017, Sec. 9.2, Note 1).
	internal static ReadOnlySpan<byte> Sha256 => [0x30, 0x31, 0x30, 0x0D, 0x06, 0x09, 0x60, 0x86, 0x48, 0x01, 0x65, 0x03, 0x04, 0x02, 0x01, 0x05, 0x00, 0x04, 0x20];

	internal static ReadOnlySpan<byte> Sha384 => [0x30, 0x41, 0x30, 0x0D, 0x06, 0x09, 0x60, 0x86, 0x48, 0x01, 0x65, 0x03, 0x04, 0x02, 0x02, 0x05, 0x00, 0x04, 0x30];

	internal static ReadOnlySpan<byte> Sha512 => [0x30, 0x51, 0x30, 0x0D, 0x06, 0x09, 0x60, 0x86, 0x48, 0x01, 0x65, 0x03, 0x04, 0x02, 0x03, 0x05, 0x00, 0x04, 0x40];

	// The same without parameters.
	internal static ReadOnlySpan<byte> Sha256WithoutParameters => [0x30, 0x2F, 0x30, 0x0B, 0x06, 0x09, 0x60, 0x86, 0x48, 0x01, 0x65, 0x03, 0x04, 0x02, 0x01, 0x04, 0x20];

	internal static ReadOnlySpan<byte> Sha384WithoutParameters => [0x30, 0x3F, 0x30, 0x0B, 0x06, 0x09, 0x60, 0x86, 0x48, 0x01, 0x65, 0x03, 0x04, 0x02, 0x02, 0x04, 0x30];

	internal static ReadOnlySpan<byte> Sha512WithoutParameters => [0x30, 0x4F, 0x30, 0x0B, 0x06, 0x09, 0x60, 0x86, 0x48, 0x01, 0x65, 0x03, 0x04, 0x02, 0x03, 0x04, 0x40];

	// Whether encoded is EMSA-PKCS1-v1_5-ENCODE of hash with digestInfo, compared byte for byte (RFC 8017, Sec. 8.2.2, step 4): the lengths of PS and T follow from k and the hash, so nothing is parsed.
	internal static bool IsEncoding(ReadOnlySpan<byte> encoded, ReadOnlySpan<byte> digestInfo, ReadOnlySpan<byte> hash)
	{
		int separator = encoded.Length - digestInfo.Length - hash.Length - 1;

		return encoded[0] is 0x00
			&& encoded[1] is 0x01
			&& !encoded.Slice(2, separator - 2).ContainsAnyExcept((byte)0xFF)
			&& encoded[separator] is 0x00
			&& encoded.Slice(separator + 1, digestInfo.Length).SequenceEqual(digestInfo)
			&& encoded.Slice(encoded.Length - hash.Length).SequenceEqual(hash);
	}
}
